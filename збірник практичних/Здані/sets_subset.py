small = {2, 4, 6}
big = {1, 2, 3, 4, 5, 6, 7}
is_sub = small.issubset(big)  # Метод .issubset() перевіряє, чи повністю покривається поточна множина іншою (чи всі її елементи присутні там)
print(is_sub)  # issubset порівнює структуру з іншою структурою, тоді як 'in' використовується для перевірки знаходження лише одного конкретного об'єкта
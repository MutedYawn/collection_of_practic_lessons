try:
    # 1. ЧИТАННЯ ФАЙЛУ
    # Конструкція with open() автоматично закриє файл, навіть якщо всередині блоку станеться аварія
    with open("number.txt", "r", encoding="utf-8") as file:
        content = file.read().strip()                                    # Зчитуємо вміст файлу та прибираємо випадкові пробіли чи переноси рядків

    # 2. ОБРОБКА ТА МАТЕМАТИЧНІ ОПЕРАЦІЇ
    number = float(content)                                              # Конвертуємо текст із файлу в число. Якщо там текст "hello" — викличе ValueError
    
    print(f"Зчитане число: {number}")
    print(f"Результат множення на 2: {number * 2}")
    
    result_div = 100 / number                                            # Ділимо 100 на наше число. Якщо у файлі був записаний "0" — викличе ZeroDivisionError
    print(f"Результат ділення 100 на число: {result_div}")

except FileNotFoundError:
    print("Помилка: файл number.txt не знайдено.")                       # Ловить помилку, якщо файлу фізично немає в папці (видалили або перейменували)

except ValueError:
    print("Помилка: у файлі має бути записане число.")                   # Ловить помилку, якщо float() натрапив на літери замість цифр

except ZeroDivisionError:
    print("Помилка: на нуль ділити не можна.")                          # Спрацьовує, якщо користувач хитро записав у файл цифру 0

finally:
    print("Роботу з файлом завершено.")                                  # Цей блок відпрацює за будь-якого фіналу (успіх чи будь-яка з трьох помилок)



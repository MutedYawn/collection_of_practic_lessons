# 1. З яких причин файл на диску може не відкритися та коли виникає FileNotFoundError?
#    - Файл може не відкритися, якщо його випадково видалили, перейменували, перенесли в іншу папку, 
#      або якщо програма шукає його не в тій директорії, де запускається. 
#    - FileNotFoundError виникає саме тоді, коли операційна система робить запит до диска за вказаним шляхом, 
#      але не знаходить файлу з точно таким ім'ям та розширенням.
#
# 2. Чому дані з текстового файлу спочатку читаються як рядок (str)?
#    - Для комп'ютера будь-який текстовий файл (.txt)  це просто послідовність символів (байтів). Python не знає, 
#      що саме ми туди записали слово чи число. Тому він завжди зчитує вміст як безпечний універсальний рядок (str), 
#      а програміст уже сам вирішує, чим цей рядок є, і за потреби конвертує його через int() або float().
#
# 3. Чому конструкція with open() зручна для роботи?
#    - Конструкція `with open()`  це менеджер контексту. Її головна суперсила в тому, що вона ГАРАНТОВАНО закриває 
#      файл (викликає метод .close()) після виходу з блоку коду. Навіть якщо всередині `with` сталася критична помилка 
#      (наприклад, ValueError чи ZeroDivisionError) і програма перервалася  файл усе одно миттєво і безпечно закриється 
#      в системі, запобігаючи витоку пам'яті чи блокуванню файлу. та ручному написанню .close().

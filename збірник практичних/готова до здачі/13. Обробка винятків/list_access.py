# 1. СТВОРЕННЯ СПИСКУ СТУДЕНТІВ
students = ["Анна", "Максим", "Олег", "Ірина", "Софія"]

# 2. ПОКАЗ СПИСКУ З ІНДЕКСАМИ ДЛЯ НАОЧНОСТІ
print("Доступні студенти та їхні індекси:")
for index, name in enumerate(students):
    print(f"Індекс {index}: {name}")                                     # Виведе на екран: Індекс 0: Анна, Індекс 1: Максим і т.д.

print("-" * 30)

try:
    # 3. ВВЕДЕННЯ ІНДЕКСУ
    user_input = input("Введіть індекс студента, якого хочете переглянути: ")
    index = int(user_input)                                              # Спроба перетворити текст на ціле число. Якщо ввести "два" — викличе ValueError
    
    # 4. ДОСТУП ДО ЕЛЕМЕНТА
    selected_student = students[index]                                   # Звертаємось до списку. Якщо ввести число менше 0 або більше 4 — викличе IndexError

except ValueError:
    print("Помилка: індекс має бути числом.")                            # Ловить помилку, якщо користувач ввів літери замість цифр

except IndexError:
    print("Помилка: студента з таким індексом немає.")                   # Ловить помилку, якщо вказане число виходить за межі списку (наприклад, 5 або 10)

else:
    print(f"Обраний студент: {selected_student}")                         # Виводить ім'я знайденого студента, якщо помилок не було
    print("Пошук виконано успішно.")                                     # Блок else відпрацьовує тільки при 100% успіху в блоці try

finally:
    print("Перевірку списку завершено.")                                 # Блок finally залізобетонно виконається в будь-якому випадку наприкінці



# 1. Що таке індекс списку і з якого числа починається індексація в Python?
#    - Індекс  це порядковий номер елемента у списку, який вказує на його точне розташування в пам'яті. 
#      В Python індексація завжди починається з числа 0 (перший елемент має індекс 0, другий — 1 і так далі).
#
# 2. Коли саме виникає помилка IndexError?
#    - IndexError виникає тоді, коли програма намагається звернутися до індексу, якого фізично не існує в даному списку. 
#      Наприклад, у нашому списку з 5 елементів максимальний індекс  це 4. Якщо ми попросимо елемент з індексом 5 або 99, 
#      Python видасть IndexError, бо таких "коробок" у списку немає.
#
# 3. Як конструкція try-except допомагає програмі продовжувати роботу, навіть якщо вказано неіснуючий індекс?
#    - Зазвичай, коли виникає IndexError, Python негайно зупиняє всю програму і показує червону помилку (аварійне завершення). 
#      Конструкція try-except перехоплює цей виняток. Замість "падіння" програми, Python просто виконує наш безпечний 
#      блок коду під словом `except IndexError`, гасить аварію і спокійно рухається далі по коду нижче.

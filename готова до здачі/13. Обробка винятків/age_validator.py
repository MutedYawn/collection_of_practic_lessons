while True:                                                               # Запускаємо нескінченний цикл, який крутитиметься до успішного break
    try:
        user_input = input("Введіть ваш вік (від 1 до 120): ")            # Запитуємо вік у користувача
        age = int(user_input)                                            # Спроба конвертувати текст у ціле число. Якщо ввести "привіт" — викличе ValueError

    except ValueError:
        print("Помилка: вік потрібно вводити числом.")                    # Перехоплюємо помилку, якщо користувач ввів літери чи символи замість цифр
        continue                                                         # Змушуємо цикл миттєво перейти на наступне коло, пропускаючи перевірки нижче

    # Перевірка діапазону (if спрацює, тільки якщо конвертація в int пройшла успішно і без помилок)
    if 1 <= age <= 120:
        print(f"Вік прийнято: {age}")                                     # Повідомляємо, що все супер
        print("Дані збережено.")                                         # Виводимо фінальне повідомлення за умовою завдання
        break                                                            # Розриваємо цикл while, оскільки дані повністю коректні
    else:
        print("Помилка: вік має бути від 1 до 120.")                     # Якщо ввели, наприклад, 500 чи -5, цикл просто йде на нове коло



# 1. Чому число 500 не викликає виняток ValueError під час конвертації, але все одно є логічно неправильним віком?
#    - Функція int() перевіряє ТІЛЬКИ тип даних. Рядок "500" складається суто з цифр, тому з точки зору Python 
#      це абсолютно валідне ціле число, і конвертація проходить без технічних помилок. Проте біологічно людина не може 
#      жити 500 років, тому це значення є ЛОГІЧНОЮ помилкою, яку мова програмування сама по собі виявити не може — 
#      для цього ми й пишемо умову `if 1 <= age <= 120`.
#
# 2. Чим відрізняється системна помилка типу даних від логічно неправильного значення?
#    - Системна помилка типу даних (як-от ValueError) виникає, коли ламаються внутрішні правила мови Python (спроба 
#      поділити строку на число або зробити int("abc")). Програма фізично не може виконати такий код і "падає".
#    - Логічно неправильне значення  це коли з точки зору Python код написаний правильно (числа додаються, списки читаються), 
#      але значення суперечать бізнес-логіці чи реальному світу (вік -10 років, ціна товару $0, баланс карти 999999999). 
#      Такі речі перевіряються звичайними операторами `if`.
#
# 3. Як поєднання циклу while та try-except дозволяє створювати стійкі до помилок користувача інтерфейси?
#    - Без цієї зв'язки будь-яка випадкова помилка користувача (натиснув не ту літеру) призводила б до аварійного завершення 
#      програми, і йому доводилося б запускати її знову. 
#    - Поєднання `while True` (який тримає програму запущеною) та `try-except` (який гасить системні аварії всередині циклу) 
#      створює "непробивний щит". Програма м'яко перехоплює будь-яку некоректну дію, виводить підказку і за допомогою 
#      наступного кола циклу дає користувачу нескінченну кількість спроб виправитися без перезапуску софту.

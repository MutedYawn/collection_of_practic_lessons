try:
    num1 = float(input("Введіть перше число: "))                       # Конвертує введення у дробове число. Якщо ввести текст — викличе ValueError
    num2 = float(input("Введіть друге число: "))                       # Якщо користувач замість цифр введе літери, Python одразу перестрибне в блок except ValueError
    
    operation = input("Оберіть операцію (+, -, *, /): ").strip()        # Запитує математичну дію та прибирає випадкові пробіли по боках

    if operation == "+":
        result = num1 + num2
    elif operation == "-":
        result = num1 - num2
    elif operation == "*":
        result = num1 * num2
    elif operation == "/":
        result = num1 / num2                                            # Якщо num2 буде дорівнювати 0, цей рядок миттєво викличе виняток ZeroDivisionError
    else:
        result = None
        print("Помилка: невідома математична операція.")                # Спрацьовує, якщо користувач ввів якийсь дивний символ замість знаків дій

except ValueError:
    print("Помилка: потрібно вводити тільки числа.")                    # Цей блок ловить помилку, якщо float() отримав літери замість цифр

except ZeroDivisionError:
    print("Помилка: на нуль ділити не можна.")                         # Цей блок рятує програму від падіння, якщо користувач спробував поділити на 0

else:
    if result is not None:
        print(f"Результат: {result}")                                   # Виводить порахований результат на екран
        print("Операція виконана успішно.")                             # Блок else виконується ТІЛЬКИ тоді, коли в try все пройшло ідеально і без помилок

finally:
    print("Роботу калькулятора завершено.")                             # Блок finally виконується ЗАВЖДИ: і при успіху, і при будь-якій помилці


# ====================================================================================================
# КОРОТКА ТЕОРІЯ 
# 1. try / except try містить "небезпечний" код, а except перехоплює помилки (винятки), щоб програма не аварійно не вилітала.
# 2. ValueError виникає, коли функція float() намагається перетворити текст (наприклад, "абв") на число.
#    ZeroDivisionError  виникає автоматично, коли математична логіка процесора натрапляє на ділення на 0.
# 3. else / finally  else запускається лише за повної відсутності помилок у try. finally залізобетонно спрацює в будь-якому випадку наприкінці.
# ====================================================================================================
grades = []                                                             # Глобальний список для збереження оцінок студента

def show_history():
    if len(grades) == 0:
        print("Щоденник порожній.")                                     # Повідомлення, якщо оцінок ще немає
    else:
        print("--- ЩОДЕННИК ---")
        for grade in grades:
            print(grade)                                                # Виводить кожну оцінку зі списку в консоль

def process_grades(grades, callback):
    if len(grades) == 0:
        print("Помилка: Список оцінок порожній! Спочатку додайте оцінки.")
        return                                                          # Блокує розрахунки та виходить, якщо список порожній
    callback(grades)                                                    # Викликає callback-функцію, яку передали як аргумент

def add_grade():
    new_grade = int(input("Введіть оцінку (від 1 до 12) \n:> "))
    if 1 <= new_grade <= 12:
        grades.append(new_grade)                                        # Додає валідну оцінку до списку
        print("Оцінку успішно додано!")
    else:
        print("Помилка! Оцінка має бути в межах від 1 до 12.")          # Повідомлення про некоректне введення

def show_avg(grades):
    avg = sum(grades) / len(grades)                                     # Обчислення середнього арифметичного значення
    print(f"Середній бал: {avg:.2f}")                                   # Вивід з округленням до 2 знаків після коми

def show_min(grades):
    sh_min = min(grades)                                                # Пошук мінімального значення у списку
    print(f"Найменша оцінка: {sh_min}")  

def show_max(grades):
    sh_max = max(grades)                                                # Пошук максимального значення у списку
    print(f"Найбільша оцінка: {sh_max}")

def show_len(grades):
    sh_len = len(grades)                                                # Визначення кількості елементів у списку
    print(f"Кількість оцінок: {sh_len}")        

while True:
    print("1. Додати Оцінку \n2. Показати всі оцінки \n3. Показати середній бал \n4. Показати найвищу оцінку \n5. Показати найнижчу оцінку \n6. Показати кількість оцінок \n7. Вийти")
    choice = input("Оберіть дію: ")
    
    if choice == "7":
        print("Вихід з програми")
        break                                                           # Зупиняє цикл і завершує додаток
        
    elif choice == "1":
        add_grade()                                                     # Прямий виклик функції додавання оцінки
        
    elif choice == "2":
        show_history()                                                  # Прямий виклик функції показу всіх оцінок
        
    elif choice == "3":
        process_grades(grades, show_avg)                                # Передача функції розрахунку середнього як callback
        
    elif choice == "4":
        process_grades(grades, show_max)                                # Передача функції пошуку максимуму як callback
        
    elif choice == "5":
        process_grades(grades, show_min)                                # Передача функції пошуку мінімуму як callback
        
    elif choice == "6":
        process_grades(grades, show_len)                                # Передача функції підрахунку кількості як callback

# ТЕОРІЯ ДО ЗАВДАННЯ:
# 1. Callback-функція це функція, яку ми передаємо як аргумент в іншу функцію, щоб та викликала її пізніше.
# 2. Передача з дужками () викликає функцію негайно на місці. Передача БЕЗ дужок передає саму функцію як об'єкт, щоб викликати її потім.
# 3. Користь callback-функцій у гнучкості: головна функція process_grades не знає, що саме робити з даними, вона просто перевіряє список і запускає ту дію, яку ми їй передали.